"""Presentation helpers for the web CRM layer."""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date, datetime
from zoneinfo import ZoneInfo

from app.attachments.marks import (
    AttachmentMark,
    match_full_attachment_mark,
    match_full_deleted_attachment_mark,
    strip_attachment_marks,
)

_CRM_TZ = ZoneInfo("America/Santiago")
_FOLLOW_UP_HEADER = re.compile(r"^\[(\d{2}/\d{2}/\d{4} \d{2}:\d{2})\]\s+(.+)$")


@dataclass(frozen=True, slots=True)
class FollowUpNote:
    timestamp: str
    author: str
    text: str
    attachments: tuple[AttachmentMark, ...] = ()
    deleted_attachments: tuple[AttachmentMark, ...] = ()


@dataclass(frozen=True, slots=True)
class ParsedLeadComments:
    original_request: str
    notes: list[FollowUpNote]
    is_fallback: bool = False


def parse_lead_comments(raw_comments: str | None) -> ParsedLeadComments:
    """Split the raw comentarios blob into original request and follow-up notes.

    The parser only recognizes the exact format generated by the current
    server-side append flow. If any block is malformed, it fails closed and
    returns the full content as the original request with no extracted notes.
    """

    raw = (raw_comments or "").strip()
    if not raw:
        return ParsedLeadComments(original_request="", notes=[])

    blocks = raw.split("\n\n")
    if len(blocks) == 1:
        return ParsedLeadComments(original_request=strip_attachment_marks(raw), notes=[])

    original_request = strip_attachment_marks(blocks[0].strip())
    notes: list[FollowUpNote] = []

    for block in blocks[1:]:
        parsed = _parse_follow_up_block(block)
        if parsed is None:
            return ParsedLeadComments(original_request=raw, notes=[], is_fallback=True)
        notes.append(parsed)

    return ParsedLeadComments(original_request=original_request, notes=notes)


def _parse_follow_up_block(block: str) -> FollowUpNote | None:
    lines = block.splitlines()
    if not lines:
        return None

    header = lines[0].strip()
    match = _FOLLOW_UP_HEADER.match(header)
    if match is None:
        return None

    body_lines = lines[1:]
    # Las marcas del servidor van al final, cada una en su propia línea; se
    # extraen solo las líneas finales que son exactamente una marca válida
    # (activa o de eliminado), conservando el orden.
    mark_lines: list[AttachmentMark] = []
    deleted_mark_lines: list[AttachmentMark] = []
    text_end = len(body_lines)
    while text_end > 0:
        mark = match_full_attachment_mark(body_lines[text_end - 1])
        if mark is not None:
            mark_lines.append(mark)
            text_end -= 1
            continue
        deleted = match_full_deleted_attachment_mark(body_lines[text_end - 1])
        if deleted is not None:
            deleted_mark_lines.append(deleted)
            text_end -= 1
            continue
        break
    mark_lines.reverse()
    deleted_mark_lines.reverse()

    text = "\n".join(body_lines[:text_end]).strip()
    text = strip_attachment_marks(text)
    return FollowUpNote(
        timestamp=match.group(1),
        author=match.group(2).strip(),
        text=text,
        attachments=tuple(mark_lines),
        deleted_attachments=tuple(deleted_mark_lines),
    )


def build_timeline_items(
    events: list[dict],
    notes: list[FollowUpNote],
    state_changes: list[dict] | None = None,
    simulations: list[dict] | None = None,
    agenda_events: list[dict] | None = None,
) -> list[dict]:
    """Merge assignment, state-change, simulation, agenda events and human notes into one timeline.

    Assignment events (migration 007), state-change events (migration 008), simulation
    events (migration 009) and agenda events (migration 011) carry full-precision
    ``fecha_hora`` (TIMESTAMPTZ); human notes carry minute-precision ``dd/mm/YYYY HH:MM``
    strings generated in America/Santiago. All are normalized to aware datetimes in
    America/Santiago for a stable descending sort.

    The sort is deterministic: primary key is the timestamp (descending) and, on an exact
    tie, a fixed source rank keeps assignment events before simulation events before
    state-change events before agenda events before notes (``event`` < ``simulation`` <
    ``state_change`` < ``agenda`` < ``note``). Python's stable sort then preserves the
    repository's own deterministic ordering (``fecha_hora DESC, id_auditoria DESC``) for
    ties within a single source.
    """
    items: list[dict] = []

    for event in events:
        timestamp = _to_santiago(event.get("fecha_hora"))
        if timestamp is None:
            continue
        items.append(
            {
                "kind": "event",
                "timestamp": timestamp,
                "display_time": timestamp.strftime("%d/%m/%Y %H:%M"),
                "actor": event.get("actor_subject"),
                "asesor_nombre": event.get("asesor_nombre"),
                "estado_anterior": event.get("estado_anterior"),
                "estado_nuevo": event.get("estado_nuevo"),
            }
        )

    for change in state_changes or []:
        timestamp = _to_santiago(change.get("fecha_hora"))
        if timestamp is None:
            continue
        items.append(
            {
                "kind": "state_change",
                "timestamp": timestamp,
                "display_time": timestamp.strftime("%d/%m/%Y %H:%M"),
                "actor": change.get("actor_subject"),
                "estado_anterior": change.get("estado_anterior"),
                "estado_nuevo": change.get("estado_nuevo"),
            }
        )

    for sim in simulations or []:
        timestamp = _to_santiago(sim.get("fecha_hora"))
        if timestamp is None:
            continue
        entradas = _normalize_simulation_entradas(sim.get("entradas"))
        resultado = _normalize_simulation_resultado(sim.get("resultado"))
        # Legacy events predate SIM-EVIDENCIA-ENTRADAS: the view returns entradas and
        # resultado as NULL, so only the root metadata survived. They are flagged so the
        # template renders the honest note instead of the (empty) detail dropdown.
        es_legacy = sim.get("entradas") is None and sim.get("resultado") is None
        items.append(
            {
                "kind": "simulation",
                "timestamp": timestamp,
                "display_time": timestamp.strftime("%d/%m/%Y %H:%M"),
                "actor": sim.get("actor_subject"),
                "tipo_escenario": sim.get("tipo_escenario"),
                "version_modelo": sim.get("version_modelo"),
                "codigo_verificacion": sim.get("codigo_verificacion"),
                "es_legacy": es_legacy,
                "pension_uf": resultado["pension_uf"],
                "renta_temporal_uf": resultado["renta_temporal_uf"],
                "meses_diferidos": resultado["meses_diferidos"],
                "entradas": entradas,
                "resultado": resultado,
            }
        )

    for agenda in agenda_events or []:
        timestamp = _to_santiago(agenda.get("fecha_hora"))
        if timestamp is None:
            continue
        fecha_hora_nueva = agenda.get("fecha_hora_nueva")
        fecha_hora_anterior = agenda.get("fecha_hora_anterior")
        # La fecha de la reunion es la nueva si existe; si no, la anterior
        # (cancelada/realizada/no asistio no tienen fecha nueva).
        reunion = fecha_hora_nueva if fecha_hora_nueva is not None else fecha_hora_anterior
        items.append(
            {
                "kind": "agenda",
                "timestamp": timestamp,
                "display_time": timestamp.strftime("%d/%m/%Y %H:%M"),
                "actor": agenda.get("actor_subject"),
                "accion": agenda.get("accion"),
                "responsable": agenda.get("responsable_nombre"),
                "fecha_reunion": _format_agenda_time(reunion),
                "fecha_anterior": _format_agenda_time(fecha_hora_anterior),
            }
        )

    for note in notes:
        items.append(
            {
                "kind": "note",
                "timestamp": _parse_note_timestamp(note.timestamp),
                "display_time": note.timestamp,
                "author": note.author,
                "text": note.text,
                "attachments": [
                    {
                        "attachment_type": mark.attachment_type,
                        "attachment_id": mark.attachment_id,
                        "scan_status": None,
                    }
                    for mark in note.attachments
                ],
                "deleted_attachments": [
                    {
                        "attachment_type": mark.attachment_type,
                        "attachment_id": mark.attachment_id,
                    }
                    for mark in note.deleted_attachments
                ],
            }
        )

    items.sort(key=_timeline_sort_key, reverse=True)
    return items


_SOURCE_RANK: dict[str, int] = {
    "event": 0,
    "simulation": 1,
    "state_change": 2,
    "agenda": 3,
    "note": 4,
}


def _timeline_sort_key(item: dict) -> tuple[datetime, int]:
    """Stable, deterministic sort key: timestamp desc, then fixed source rank asc."""
    return (item["timestamp"], -_SOURCE_RANK[item["kind"]])


def _normalize_simulation_entradas(entradas: dict | None) -> dict:
    """Normalize a simulation ``entradas`` payload into a template-safe shape.

    The evidence has had two forms over time: legacy rows (pre SIM-EVIDENCIA-ENTRADAS)
    have no ``entradas`` at all, and newer rows may still be partial (missing causante,
    empty beneficiarios, null dates). Every leaf is normalized to a fixed key with a
    ``None`` fallback so the Jinja template never chains attribute access on an
    undefined value (``item.entradas.causante.sexo`` would otherwise raise
    ``UndefinedError``).
    """
    data = entradas or {}
    causante = data.get("causante") or {}
    beneficiarios = data.get("beneficiarios") or []
    return {
        "fecha_simulacion": data.get("fecha_simulacion"),
        "saldo_uf": data.get("saldo_uf"),
        "tasa_venta_pct": data.get("tasa_venta_pct"),
        "valor_uf": data.get("valor_uf"),
        "meses_garantizados": data.get("meses_garantizados"),
        "meses_aumento_temporal": data.get("meses_aumento_temporal"),
        "pct_aumento_temporal": data.get("pct_aumento_temporal"),
        "anios_diferidos": data.get("anios_diferidos"),
        "porcentaje_rvd": data.get("porcentaje_rvd"),
        "causante": {
            "sexo": causante.get("sexo"),
            "fecha_nacimiento": causante.get("fecha_nacimiento"),
        },
        "beneficiarios": [
            {
                "parentesco": b.get("parentesco"),
                "sexo": b.get("sexo"),
                "fecha_nacimiento": b.get("fecha_nacimiento"),
                "invalidez": b.get("invalidez"),
                "comun": b.get("comun"),
            }
            for b in beneficiarios
            if isinstance(b, dict)
        ],
    }


def _normalize_simulation_resultado(resultado: dict | None) -> dict:
    """Normalize a simulation ``resultado`` payload into a template-safe shape."""
    data = resultado or {}
    return {
        "pension_uf": data.get("pension_uf"),
        "renta_temporal_uf": data.get("renta_temporal_uf"),
        "meses_diferidos": data.get("meses_diferidos"),
    }


def _to_santiago(value: object) -> datetime | None:
    """Normalize a database timestamp to an aware America/Santiago datetime."""
    if value is None or not isinstance(value, datetime):
        return None
    if value.tzinfo is None:
        return value.replace(tzinfo=_CRM_TZ)
    return value.astimezone(_CRM_TZ)


def _format_agenda_time(value: object) -> str | None:
    """Format an agenda meeting timestamp as ``DD/MM/YYYY HH:MM`` in America/Santiago."""
    ts = _to_santiago(value)
    if ts is None:
        return None
    return ts.strftime("%d/%m/%Y %H:%M")


def _parse_note_timestamp(value: str) -> datetime:
    """Parse a follow-up note timestamp written by the server in America/Santiago."""
    try:
        return datetime.strptime(value, "%d/%m/%Y %H:%M").replace(tzinfo=_CRM_TZ)
    except ValueError:
        return datetime.min.replace(tzinfo=_CRM_TZ)


def state_history_cutover_notice(cutover: date | None) -> str:
    """Build the honest coverage notice for general state-change history.

    The cutover date is never invented during development: it comes from a
    reproducible configuration source (``LEAD_STATE_HISTORY_CUTOVER``). When it is
    not configured, the notice states the coverage boundary without a fake date.
    """
    if cutover is None:
        return (
            "El historial de cambios generales de estado se muestra desde la "
            "puesta en produccion de la migracion 008. Las asignaciones "
            "anteriores se conservan."
        )
    return (
        f"El historial de cambios generales de estado se muestra desde el "
        f"{cutover.strftime('%d/%m/%Y')} (corte de la migracion 008). Las "
        "asignaciones anteriores se conservan."
    )
